// الهدف الحالي يُشتق من الحالة (لا يُخزَّن) — يسهّل الحفظ والتراجع
export function deriveObjective(s) {
  if (s.ending) return { id: 'done', text: 'انتهت المهمة. يمكنك التجوّل في الحارة بحرية.' };
  if (!s.flag('met_aj')) return { id: 'talk_aj', text: 'تكلّم مع أبو جلال في المقهى.' };
  if (s.hasItem('watch')) return { id: 'return_watch', text: 'أعد الساعة إلى أبو جلال في المقهى.' };
  if (s.flag('um_confessed') || s.hasClue('c_prints')) return { id: 'search_niche', text: 'فتّش المصطبة الحجرية على الجانب الغربي من الساحة.' };
  return { id: 'investigate', text: 'ابحث عن ساعة الجيب: افحص الطاولة، واسأل أهل الحارة.' };
}

export function leads(s) {
  return [
    { text: 'افحص الطاولة الخلفية في المقهى', done: s.hasClue('c_chain') },
    { text: 'تحدّث إلى العكيد', done: s.flag('met_aq') },
    { text: 'تحدّث إلى أم حسن', done: s.flag('met_um') },
    { text: 'افحص آثار الأقدام قرب البحرة', done: s.hasClue('c_prints') },
    { text: 'فتّش المصطبة الحجرية', done: s.hasItem('watch') || !!s.ending },
    { text: 'أعد الساعة إلى أبو جلال', done: !!s.ending },
  ];
}

