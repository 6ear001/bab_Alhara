// فحص الأغراض في العالم: يعيد أسطر «أفكار نديم» + تأثيرات. محتوى أصلي.
export const EXAMINE = {
  table: (s) => {
    if (s.hasClue('c_chain')) return { lines: ['فحصت الطاولة مرة تانية… ما في شي جديد.'] };
    return {
      lines: ['تحت الطاولة الخلفية… (ينحني) هالسلسلة النحاسية! حلقتها مقطوعة بقوة.', 'وعليها بصمة أصابع صغيرة… مو إيد رجّال أبداً. يعني الساعة انسرقت، ما ضاعت.'],
      fx: { item: 'chain', clue: 'c_chain' },
    };
  },
  prints: (s) => {
    if (s.hasClue('c_prints')) return { lines: ['آثار الأقدام الصغيرة ما زالت هون… بتروح باتجاه المصطبة الحجرية.'] };
    return {
      lines: s.hasItem('chain')
        ? ['آثار أقدام صغيرة مبلولة… بتبدأ من حافة البحرة وبتتجه غرباً.', 'بنفس حجم البصمة يلي عالسلسلة… ولد. وبتودّي عالمصطبة الحجرية.']
        : ['آثار أقدام صغيرة مبلولة… بتبدأ من حافة البحرة وبتتجه غرباً، نحو المصطبة الحجرية.'],
      fx: { clue: 'c_prints' },
    };
  },
  niche: (s) => {
    if (s.hasItem('watch') || s.ending) return { lines: ['المخبأ فاضي هلق.'] };
    if (s.hasClue('c_prints') || s.hasClue('c_hint')) {
      return {
        lines: ['حجر سائب بالمصطبة… (يزيحه بحذر)', 'الساعة! ما زالت تدقّ… الله يستر عليك يا حسن. هلق لازم قرّر شو أعمل.'],
        fx: { item: 'watch', clue: 'c_watch', flag: { found_watch: true } },
      };
    }
    return { lines: ['حجارة المصطبة… ما في شي يلفت النظر.'] };
  },
  gate: () => ({ lines: ['باب الحارة… ما في داعي أطلع منو هلق. الحارة كلها هون، وحكايتها كلها هون.'] }),
  fountain: () => ({ lines: ['بحرة الحارة… صوت المي بيريّح الأعصاب. من هون بتشوف كل الحارة وناسها.'] }),
};
